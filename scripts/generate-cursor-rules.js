#!/usr/bin/env node

/**
 * Generate Cursor Rules from GitHub Instructions
 *
 * This script converts `.github/instructions/*.instructions.md` files
 * to Cursor's `.cursor/rules/*.mdc` format.
 *
 * Usage:
 *   node scripts/generate-cursor-rules.js
 *   or
 *   pnpm cursor:sync
 */

import fs from 'node:fs'
import path, { dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

// Get __dirname equivalent in ES modules
const __filename = fileURLToPath(import.meta.url)
const __dirname = dirname(__filename)

// Paths
const GITHUB_INSTRUCTIONS_DIR = path.join(__dirname, '..', '.github', 'instructions')
const CURSOR_RULES_DIR = path.join(__dirname, '..', '.cursor', 'rules')

/**
 * Parse YAML frontmatter from markdown content
 * Returns { frontmatter: {}, content: string }
 */
function parseFrontmatter(content) {
  const frontmatterRegex = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/
  const match = content.match(frontmatterRegex)

  if (!match) {
    return { frontmatter: {}, content: content.trim() }
  }

  const frontmatterText = match[1]
  const markdownContent = match[2].trim()

  // Simple YAML parser for our specific fields
  const frontmatter = {}
  const lines = frontmatterText.split('\n')

  for (const line of lines) {
    const colonIndex = line.indexOf(':')
    if (colonIndex === -1) continue

    const key = line.slice(0, colonIndex).trim()
    const value = line.slice(colonIndex + 1).trim()

    frontmatter[key] = value
  }

  return { frontmatter, content: markdownContent }
}

/**
 * Expand brace patterns in glob strings
 * Example: "apps/**\/*.{ts,tsx}" -> ["apps/**\/*.ts", "apps/**\/*.tsx"]
 */
function expandBraces(pattern) {
  const braceRegex = /\{([^}]+)\}/
  const match = pattern.match(braceRegex)

  if (!match) {
    return [pattern]
  }

  const options = match[1].split(',').map((s) => s.trim())
  const prefix = pattern.slice(0, match.index)
  const suffix = pattern.slice(match.index + match[0].length)

  return options.map((opt) => prefix + opt + suffix)
}

/**
 * Create Cursor-compatible frontmatter
 */
function createCursorFrontmatter(githubFrontmatter) {
  const cursorFrontmatter = {}

  // Copy description
  if (githubFrontmatter.description) {
    cursorFrontmatter.description = githubFrontmatter.description
  }

  // Convert applyTo to globs array
  if (githubFrontmatter.applyTo) {
    const globs = expandBraces(githubFrontmatter.applyTo)
    cursorFrontmatter.globs = globs
  }

  // Return YAML string
  if (Object.keys(cursorFrontmatter).length === 0) {
    return ''
  }

  let yaml = '---\n'
  if (cursorFrontmatter.description) {
    yaml += `description: ${cursorFrontmatter.description}\n`
  }
  if (cursorFrontmatter.globs) {
    yaml += `globs: ${JSON.stringify(cursorFrontmatter.globs)}\n`
  }
  yaml += '---\n\n'

  return yaml
}

/**
 * Convert GitHub instruction file to Cursor MDC format
 */
function convertToMdc(content, filename) {
  // Parse GitHub frontmatter and content
  const { frontmatter, content: markdownContent } = parseFrontmatter(content)

  // Create Cursor frontmatter
  const cursorFrontmatter = createCursorFrontmatter(frontmatter)

  // Add Cursor-specific header
  const title = filename.replace('.instructions.md', '').replace(/-/g, ' ')
  const header = `# ${title.charAt(0).toUpperCase() + title.slice(1)}\n\n`

  // Add note about auto-generation
  const note = `> **Note:** This file is auto-generated from \`.github/instructions/${filename}\`.\n> DO NOT edit this file directly. Edit the source file and run \`pnpm cursor:sync\`.\n\n---\n\n`

  return cursorFrontmatter + header + note + markdownContent
}

/**
 * Ensure directory exists
 */
function ensureDir(dir) {
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true })
    console.log(`✅ Created directory: ${dir}`)
  }
}

/**
 * Main conversion function
 */
function generateCursorRules() {
  console.log('🔄 Converting GitHub instructions to Cursor rules...\n')

  // Ensure directories exist
  ensureDir(CURSOR_RULES_DIR)

  // Read all instruction files
  const files = fs
    .readdirSync(GITHUB_INSTRUCTIONS_DIR)
    .filter((file) => file.endsWith('.instructions.md'))

  if (files.length === 0) {
    console.log('⚠️  No instruction files found in .github/instructions/')
    return
  }

  let converted = 0
  let errors = 0

  // Convert each file
  for (const file of files) {
    try {
      const sourcePath = path.join(GITHUB_INSTRUCTIONS_DIR, file)
      const targetPath = path.join(CURSOR_RULES_DIR, file.replace('.instructions.md', '.mdc'))

      // Read source file
      const content = fs.readFileSync(sourcePath, 'utf-8')

      // Convert to MDC format
      const mdc = convertToMdc(content, file)

      // Write target file
      fs.writeFileSync(targetPath, mdc, 'utf-8')

      console.log(`✅ ${file} → ${path.basename(targetPath)}`)
      converted++
    } catch (error) {
      console.error(`❌ Error converting ${file}:`, error.message)
      errors++
    }
  }

  // Summary
  console.log('\n📊 Conversion complete:')
  console.log(`   ✅ Converted: ${converted} files`)
  if (errors > 0) {
    console.log(`   ❌ Errors: ${errors} files`)
  }
  console.log(`\n📁 Cursor rules generated in: ${CURSOR_RULES_DIR}`)
  console.log('\n💡 Tip: Open your project in Cursor to use these rules.')
}

// Run the script
try {
  generateCursorRules()
} catch (error) {
  console.error('❌ Fatal error:', error.message)
  process.exit(1)
}
